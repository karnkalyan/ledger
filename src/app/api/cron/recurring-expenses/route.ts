import { NextRequest, NextResponse } from "next/server";
import { addDays, endOfDay, endOfMonth, startOfDay, startOfMonth } from "date-fns";
import { Prisma } from "@/generated/client";
import { db } from "@/lib/db";
import { estimateRecurringExpense } from "@/lib/expense-engine";

export const runtime = "nodejs";

export async function GET(request: NextRequest) {
  const secret = process.env.CRON_SECRET;
  if (secret && request.headers.get("authorization") !== `Bearer ${secret}`) return NextResponse.json({error:"Unauthorized"},{status:401});
  const now=new Date(), monthStart=startOfMonth(now), monthEnd=endOfMonth(now);
  const recurring=await db.recurringExpense.findMany({where:{active:true,startDate:{lte:monthEnd},OR:[{endDate:null},{endDate:{gte:monthStart}}]}});
  let estimates=0, reminders=0, licenses=0;
  for(const item of recurring){
    const exists=await db.expense.findFirst({where:{recurringExpenseId:item.id,isEstimated:true,occurredAt:{gte:monthStart,lte:monthEnd}}});
    if(!exists){
      const amount=estimateRecurringExpense(item,now);
      if(amount>0){await db.expense.create({data:{organizationId:item.organizationId,categoryId:item.categoryId,recurringExpenseId:item.id,title:`${item.title} — monthly estimate`,vendor:item.vendor,type:"RECURRING",quantity:item.quantity,unit:item.unit,unitRate:item.unitRate,daysCount:item.recurrence==='DAILY'?(item.billingDays??new Prisma.Decimal(new Date(now.getFullYear(),now.getMonth()+1,0).getDate())):item.billingDays,amount,occurredAt:monthStart,isEstimated:true,notes:"Auto-generated by recurring expense scheduler"}});estimates++;}
    }
    if(item.dayOfMonth){
      const day=Math.min(item.dayOfMonth,new Date(now.getFullYear(),now.getMonth()+1,0).getDate()); const due=new Date(now.getFullYear(),now.getMonth(),day,12); const reminderDate=addDays(due,-item.reminderDaysBefore);
      if(now>=startOfDay(reminderDate)&&now<=endOfDay(due)){
        const existingReminder=await db.reminder.findFirst({where:{organizationId:item.organizationId,referenceType:"RECURRING_EXPENSE",referenceId:item.id,dueAt:{gte:startOfDay(due),lte:endOfDay(due)}}});
        if(!existingReminder){await db.reminder.create({data:{organizationId:item.organizationId,title:`Due: ${item.title}`,dueAt:due,referenceType:"RECURRING_EXPENSE",referenceId:item.id,notes:item.vendor?`Payable to ${item.vendor}`:null}});reminders++;}
      }
    }
  }
  const expiring=await db.licenseRecord.findMany({where:{expiryDate:{not:null},status:{in:["ACTIVE","EXPIRING"]}}});
  for(const license of expiring){
    if(!license.expiryDate)continue; const days=(license.expiryDate.getTime()-now.getTime())/86400000;
    if(days<0){await db.licenseRecord.update({where:{id:license.id},data:{status:"EXPIRED"}});licenses++;continue;}
    if(days<=30){await db.licenseRecord.update({where:{id:license.id},data:{status:"EXPIRING"}}); const exists=await db.reminder.findFirst({where:{organizationId:license.organizationId,referenceType:"LICENSE",referenceId:license.id,status:"PENDING"}}); if(!exists){await db.reminder.create({data:{organizationId:license.organizationId,title:`Renew license: ${license.name}`,dueAt:license.expiryDate,referenceType:"LICENSE",referenceId:license.id,notes:license.vendor?`Vendor: ${license.vendor}`:null}});reminders++;} licenses++;}
  }
  return NextResponse.json({ok:true,estimatesCreated:estimates,remindersCreated:reminders,licensesUpdated:licenses});
}
